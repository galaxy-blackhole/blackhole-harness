import { boundContextSummary, createUserMessage as kernelCreateUserMessage } from "@deepseek-ai/dsh-llm";
import type { AgentUserMessage, ModelSelection, ModelSelectionContext, ModelSelectionRef } from "./types.ts";

/** Đầu vào của `createUserMessage` mà row này dựng — nguồn `model-selection` là của CHÍNH row này. */
interface ModelNoticeInput {
  /** Các khối nội dung của thông báo. */
  readonly content: readonly { readonly type: "text"; readonly text: string }[];
  /** Nguồn đã khai: một `notice` của bộ chọn model, kèm câu tóm tắt MỘT DÒNG đã bị chặn độ dài. */
  readonly source: {
    readonly kind: "model-selection";
    readonly form: "notice";
    readonly summary: string;
  };
}

/**
 * Hàm dựng thông điệp của KERNEL, dưới hình dạng mà row này cần.
 *
 * Vì sao không tự dựng: thông điệp phải là ĐÚNG biểu diễn của kernel (id có thương hiệu, vật đã
 * đóng băng sâu qua `structuredClone`) vì nó đi vào nhật ký phiên; viết lại tay sẽ lệch hình dạng.
 * Vì sao phải đổi kiểu: `model-selection.d.ts` của gói GỐC đã augment `MessageSourceMap` của
 * `dsh-llm`; khai thêm một augmentation nữa trong cùng chương trình `tsc` là đỏ TS2717 (đo thật
 * với row `system-prompt`, 18/10/2026) — nên nguồn `model-selection` được khai CỤC BỘ ở đây.
 */
const createUserMessage = kernelCreateUserMessage as unknown as (input: ModelNoticeInput) => AgentUserMessage;

/**
 * Hai tuyến có CÙNG route provider/model không (bỏ qua mức suy luận).
 * Nhận: `left` · `right` — hai tuyến cần so.
 * Trả: `true` khi provider và model trùng nhau.
 */
function sameRoute(left: ModelSelection, right: ModelSelection): boolean {
  return left.provider === right.provider && left.model === right.model;
}

/**
 * Nhãn hiển thị của MỘT tuyến so với tuyến kia: cùng provider thì chỉ tên model, khác thì
 * `provider/model`.
 * Nhận: `route` — tuyến cần dán nhãn; `other` — tuyến đối chiếu.
 * Trả: chuỗi nhãn.
 */
function routeLabel(route: ModelSelection, other: ModelSelection): string {
  return route.provider === other.provider ? route.model : `${route.provider}/${route.model}`;
}

/**
 * Dựng thông điệp người-dùng BỀN báo rằng tuyến model vừa đổi.
 * Nhận: `previous` — tuyến của đầu mục request gần nhất; `selected` — tuyến vừa chọn.
 * Trả: thông điệp đã đóng băng, nguồn `model-selection`, tóm tắt `from → to` đã chặn độ dài.
 */
function modelSwitchNotice(previous: ModelSelection, selected: ModelSelection): AgentUserMessage {
  const from = routeLabel(previous, selected);
  const to = routeLabel(selected, previous);
  return createUserMessage({
    content: [{
      type: "text",
      text: `[model changed: assistant turns above this point were generated by ${from}; the session continues with ${to}]`,
    }],
    source: {
      kind: "model-selection",
      form: "notice",
      summary: boundContextSummary(`${from} → ${to}`),
    },
  });
}

/**
 * Ghép MỘT lựa chọn thay đổi được vào phép lắp prompt và định tuyến request theo scope của agent.
 * Phép lắp chụp model đã chọn TRƯỚC khi chuyển tiếp, rồi áp cặp provider/model và mức suy luận vào
 * cấu hình request, nên một lần đổi giữa chừng chỉ có hiệu lực ở bước SAU thay vì tách đôi hai bề
 * mặt. Mức suy luận vắng mặt XOÁ mức kế thừa, trả lại hành vi mặc định của provider/model đã chọn.
 *
 * Một lần đổi provider/model nối một thông báo người-dùng BỀN vào request ĐƯỢC NHẬN kế tiếp. Nó so
 * lựa chọn đã lắp với đầu mục request gần nhất; đổi riêng mức suy luận và quyết định "không request"
 * rỗng đều KHÔNG thêm thông báo. Hỏng trước khi đầu mục được ghi bền thì thông báo được lặp lại ở
 * request kế tiếp.
 * Nhận: `agentCtx` — context theo scope của agent đã chọn; `selection` — lựa chọn thay đổi được do
 * điểm vào gọi sở hữu.
 * Trả: hàm dọn cho MỌI listener waterfall theo scope.
 */
export function installModelSelection(agentCtx: ModelSelectionContext, selection: ModelSelectionRef): () => void {
  const disposeAssembly = agentCtx.on("system-prompt/assemble", async (_assembly, _context, next) => {
    const selected = selection.current;
    const assembled = await next();
    selection.assembled = selected;
    if (selected === undefined) return assembled;
    return {
      ...assembled,
      variables: {
        ...assembled.variables,
        provider: selected.provider,
        model: selected.model,
      },
    };
  });
  const disposeRequest = agentCtx.on("agent/request", async (_payload, next) => {
    const resolved = await next();
    const selected = selection.assembled;
    if (selected === undefined) return resolved;
    const { reasoningEffort: _inheritedEffort, ...withoutInheritedEffort } = resolved;
    return {
      ...withoutInheritedEffort,
      provider: selected.provider,
      model: selected.model,
      ...(selected.reasoningEffort === undefined ? {} : { reasoningEffort: selected.reasoningEffort }),
    };
  });
  const disposeNotice = agentCtx.on("agent/pre-step", async ({ agent, messages, signal, step }, next) => {
    const decision = await next();
    // Hai vế của điều kiện gốc được TÁCH đôi: cùng kết cục và cùng thứ tự đọc (vế sau chỉ được đọc
    // khi vế trước sai), nhưng chỉ cách này mới hẹp được `decision` xuống nhánh `enter` ở tầng kiểu.
    if (decision.kind === "reject") return decision;
    if (signal.aborted) return decision;
    if (decision.messages.length === 0 && (step === 1 || messages.length > 0)) return decision;
    const selected = selection.assembled;
    const previous = agent.session.requestHeader()?.config;
    if (selected === undefined || previous === undefined || sameRoute(selected, previous)) return decision;
    return {
      ...decision,
      messages: [...decision.messages, modelSwitchNotice(previous, selected)],
    };
  }, { prepend: true });
  return () => {
    disposeAssembly();
    disposeRequest();
    disposeNotice();
  };
}
